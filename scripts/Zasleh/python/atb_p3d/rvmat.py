"""Text of an .rvmat: the stage layouts of a few shaders, as the game's own files have them"""

from typing import Dict, Tuple

# what the game's files put where a material has no map of the kind
NOHQ = "#(argb,8,8,3)color(0.5,0.5,1,1,NOHQ)"
SMDI = "#(argb,8,8,3)color(1,0,1,0,SMDI)"
DETAIL = "#(argb,8,8,3)color(0.5,0.5,0.5,0.5,DT)"
MACRO = "#(argb,8,8,3)color(0,0,0,0,MC)"
AMBIENT_SHADOW = "#(argb,8,8,3)color(1,1,1,1,AS)"
FRESNEL = "#(ai,64,64,1)fresnel(0.4,0.2)"
ENVIRONMENT = "a3\\data_f\\env_land_co.paa"
CHROME = "a3\\data_f\\env_chrome_co.paa"

DEFAULT = "Super"
# preset -> the maps of the material it has a stage for
MAPS: Dict[str, Tuple[str, ...]] = {
    "Super": ("normal", "detail", "specular"),
    "NormalSpecular": ("normal", "specular"),
    "Detail": ("normal", "detail", "specular"),
    "Glass": (),
}
PRESETS = tuple(MAPS)

_TRANSFORM = '''    class uvTransform
    {
        aside[]={1,0,0};
        up[]={0,1,0};
        dir[]={0,0,0};
        pos[]={0,0,0};
    };
'''


def _head(colour: str, emissive: str, power: int, pixel: str, vertex: str, extra: str = "") -> str:
    return ("// Generated by Zasleh\n"
            "ambient[]={%s};\ndiffuse[]={%s};\nforcedDiffuse[]={0,0,0,0};\nemmisive[]={%s};\nspecular[]={%s};\n"
            "specularPower=%d;\n%sPixelShaderID=\"%s\";\nVertexShaderID=\"%s\";\n"
            % (colour, colour, emissive, colour, power, extra, pixel, vertex))


def _stages(*stages) -> str:
    out = []
    for number, stage in enumerate(stages, 1):
        texture, source, extra = tuple(stage) + ("tex", "")[len(stage) - 1:]
        out.append('class Stage%d\n{\n    texture="%s";\n%s    uvSource="%s";\n%s};\n'
                   % (number, texture, extra, source, _TRANSFORM if source != "none" else ""))
    return "".join(out)


def text(preset: str = DEFAULT, normal: str = "", specular: str = "", detail: str = "") -> str:
    """The .rvmat of a preset. A map left out becomes the plain value the game uses for "none"."""
    normal, specular, detail = normal or NOHQ, specular or SMDI, detail or DETAIL
    if preset == "Super":
        return _head("1,1,1,1", "0,0,0,1", 30, "Super", "Super") + _stages(
            (normal,), (detail,), (MACRO,), (AMBIENT_SHADOW,), (specular,), (FRESNEL,),
            (ENVIRONMENT, "tex", '    useWorldEnvMap="true";\n'))
    if preset == "NormalSpecular":
        return _head("1,1,1,1", "0,0,0,1", 64, "NormalMapSpecularDIMap", "NormalMap") + _stages((normal,), (specular,))
    if preset == "Detail":
        return _head("1,1,1,1", "0,0,0,1", 30, "NormalMapDetailSpecularDIMap", "NormalMap") + _stages(
            (normal,), (detail,), (specular,))
    if preset == "Glass":
        return _head("1,1,1,0", "0,0,0,0", 10, "Glass", "Glass", 'renderFlags[]={"NoAlphaWrite"};\n') + _stages(
            ("#(argb,8,8,3)color(1,1,1,0.9)", "none"), (CHROME, "none"))
    raise ValueError("no such .rvmat preset: %s" % preset)
