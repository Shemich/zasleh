"""Point and face flag bits, as Object Builder has them"""

# point flags
POINT_ONLAND = 0x1
POINT_UNDERLAND = 0x2
POINT_ABOVELAND = 0x4
POINT_KEEPLAND = 0x8
POINT_LAND_MASK = 0xF

POINT_NOLIGHT = 0x10
POINT_AMBIENT = 0x20
POINT_FULLLIGHT = 0x40
POINT_HALFLIGHT = 0x80
POINT_LIGHT_MASK = 0xF0

POINT_DECAL = 0x100
POINT_VDECAL = 0x200
POINT_DECAL_MASK = 0x300

POINT_NOFOG = 0x1000
POINT_SKYFOG = 0x2000
POINT_FOG_MASK = 0x3000

POINT_USER_MASK = 0xFF0000
POINT_USER_STEP = 0x010000

POINT_SPECIAL_MASK = 0xF000000
POINT_SPECIAL_HIDDEN = 0x1000000
POINT_SPECIAL_LOCKNORMAL = 0x2000000     # normal is locked, O2 doesn't recalculate it
POINT_SPECIAL_ANGLENORMAL = 0x4000000    # normal weighted by face angle instead of face size

# face flags
FACE_NOLIGHT = 0x1
FACE_AMBIENT = 0x2
FACE_FULLLIGHT = 0x4
FACE_BOTHSIDESLIGHT = 0x20
FACE_SKYLIGHT = 0x80
FACE_REVERSELIGHT = 0x100000
FACE_FLATLIGHT = 0x200000
FACE_LIGHT_MASK = 0x3000A7

FACE_ISSHADOW = 0x8
FACE_NOSHADOW = 0x10
FACE_SHADOW_MASK = 0x18

FACE_Z_BIAS_MASK = 0x300
FACE_Z_BIAS_STEP = 0x100

FACE_COLORIZE_MASK = 0xF000
FACE_COLORIZE_STEP = 0x1000
FACE_COLORIZE_SHIFT = 12

FACE_FANSTRIP_MASK = 0xF0000

FACE_PROXY_VISIBLE = 0x800000
FACE_DISABLE_TEXMERGE = 0x1000000

FACE_USER_MASK = 0xFE000000
FACE_USER_STEP = 0x02000000
FACE_USER_SHIFT = 25
